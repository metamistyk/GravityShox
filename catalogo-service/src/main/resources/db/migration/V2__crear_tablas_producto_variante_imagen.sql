CREATE TABLE producto (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca_id      BIGINT        NOT NULL REFERENCES marca (id),
    categoria_id  BIGINT        NOT NULL REFERENCES categoria (id),
    nombre        VARCHAR(150)  NOT NULL,
    descripcion   TEXT,
    precio        NUMERIC(10,2) NOT NULL CHECK (precio >= 0),
    genero        VARCHAR(20)   NOT NULL,
    activo        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE variante (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id  BIGINT       NOT NULL REFERENCES producto (id) ON DELETE CASCADE,
    sku          VARCHAR(40)  NOT NULL UNIQUE,
    talla        NUMERIC(3,1) NOT NULL CHECK (talla > 0),
    color        VARCHAR(40)  NOT NULL,
    stock        INTEGER      NOT NULL DEFAULT 0 CHECK (stock >= 0),
    CONSTRAINT uq_variante_producto_talla_color UNIQUE (producto_id, talla, color)
);

CREATE TABLE imagen (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id  BIGINT       NOT NULL REFERENCES producto (id) ON DELETE CASCADE,
    url          VARCHAR(500) NOT NULL,
    color        VARCHAR(40),
    orden        INTEGER      NOT NULL DEFAULT 0
);

CREATE INDEX idx_producto_marca     ON producto (marca_id);
CREATE INDEX idx_producto_categoria ON producto (categoria_id);
CREATE INDEX idx_imagen_producto    ON imagen (producto_id);